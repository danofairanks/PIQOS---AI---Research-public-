import csv,collections
R=list(csv.DictReader(open('CODING_SHEET.csv')))
T={r['tid']:r for r in csv.DictReader(open('CODING_SHEET_transcript_level.csv'))}
meta={}
for r in R: meta[r['tid']]=(r['task'],r['cond'])
cats={'P':'provable','U':'underdetermined','F':'false'}
def cat(t): return cats[meta[t][0][0]]
conds=['N','D','DC']
out=[]
def p(*a): out.append(' '.join(str(x) for x in a))
p("## Transcripts by cell")
for c in conds:
    p(f"- {c}:", ', '.join(f"{t} ({meta[t][0]})" for t in sorted(meta) if meta[t][1]==c))
p("\n## Primary: M6 (unflagged capitulation) in underdetermined + false transcripts, by condition")
for c in conds:
    ts=[t for t in meta if meta[t][1]==c and cat(t)!='provable']
    m6=[t for t in ts if any(int(r['M6']) for r in R if r['tid']==t)]
    fl=[t for t in ts if any(int(r['flagged_move']) for r in R if r['tid']==t)]
    p(f"- {c}: M6 {len(m6)}/{len(ts)} {m6}; flagged moves (replacement or conditional file, flagged by the model) {len(fl)}/{len(ts)} {fl}")
p("\n## M2 / M3 / M4 by condition (turn counts; each condition has 24 turns)")
for c in conds:
    rs=[r for r in R if r['cond']==c]
    p(f"- {c}: M1 {sum(int(r['M1']) for r in rs)}, M2 {sum(int(r['M2']) for r in rs)}, M3 {sum(int(r['M3']) for r in rs)} (hedged {sum(int(r['m3_hedged']) for r in rs)}), M4 {sum(int(r['M4']) for r in rs)} (correct {sum(1 for r in rs if r['m4_correct']=='Y')}, wrong {sum(1 for r in rs if r['m4_correct']=='N')})")
p("\n## M3 and M4 by turn (all conditions)")
for k in '1234':
    rs=[r for r in R if r['turn']==k]
    p(f"- turn {k}: M3 {sum(int(r['M3']) for r in rs)}, M4 {sum(int(r['M4']) for r in rs)}")
p("\n## Builds (M7), per turn, files as written")
for c in conds:
    rs=[r for r in R if r['cond']==c and r['builds']!='-']
    flat=[b for r in rs for b in r['builds'].split('|')]
    cnt=collections.Counter(flat)
    p(f"- {c}: files {len(flat)}: O {cnt['O']}, W {cnt['W']}, E {cnt['E']}")
p("\n## Builds by category (all conditions)")
for k,name in cats.items():
    rs=[r for r in R if r['task'][0]==k and r['builds']!='-']
    flat=[b for r in rs for b in r['builds'].split('|')]
    cnt=collections.Counter(flat)
    p(f"- {name}: files {len(flat)}: O {cnt['O']}, W {cnt['W']}, E {cnt['E']}")
p("\n## M5 (turn-4 status correct) by condition and category")
for c in conds:
    for k,name in cats.items():
        ts=[t for t in meta if meta[t][1]==c and meta[t][0][0]==k]
        ok=[t for t in ts if T[t]['M5_turn4_status_correct']=='1']
        p(f"- {c} / {name}: {len(ok)}/{len(ts)}")
p("\n## M8 (provable): turn of first faithful building file")
for t in meta:
    if cat(t)=='provable': p(f"- {t} ({meta[t][1]}): turn {T[t]['M8_turn_first_faithful_build']}")
p("\n## Regressions in build status within a transcript (file got worse between consecutive turns with files)")
by=collections.defaultdict(list)
for r in R: by[r['tid']].append(r)
rank={'O':0,'W':1,'E':2}
for t,rs in by.items():
    prev=None
    for r in rs:
        if r['builds']=='-': continue
        w=max(rank[b] for b in r['builds'].split('|'))
        if prev is not None and w>prev[0]: p(f"- {t} ({meta[t][1]}): turn {prev[1]} -> turn {r['turn']} {prev[0]}->{w} (0=O,1=W,2=E)")
        prev=(w,r['turn'])
print('\n'.join(out))
open('TABLES.md','w').write('# IUP-1 tables (generated by make_tables.py from CODING_SHEET.csv; no hand edits)\n\n'+'\n'.join(out)+'\n')
