import sys,re,os,json,glob
from pypdf import PdfReader
import logging; logging.disable(logging.CRITICAL)
root=sys.argv[1]; out=sys.argv[2]
rows=[]
for f in sorted(glob.glob(root+'/generated-papers/*/*.pdf')):
    try:
        r=PdfReader(f); n=len(r.pages)
        txt='\n'.join((p.extract_text() or '') for p in r.pages)
    except Exception as e:
        rows.append({'file':f.split('generated-papers/')[1],'error':str(e)[:80]}); continue
    # body = text before the reference list heading (last occurrence of REFERENCES/References heading)
    m=[x.start() for x in re.finditer(r'\n\s*(REFERENCES|References)\s*\n',txt)]
    body=txt[:m[-1]] if m else txt
    low=txt.lower(); blow=body.lower()
    rows.append({'file':f.split('generated-papers/')[1],'pages':n,'words':len(txt.split()),
     'anon':'anonymous authors' in low,'iclr_header':bool(re.search(r'under review as a conference paper at iclr',low)),
     'ai_disclosure':bool(re.search(r'ai-generated|generated by (an )?(ai|llm)|scientisttwo|autonomous(ly)? generated|machine-generated',low)),
     'code_url':bool(re.search(r'github\.com|4open\.science|huggingface\.co|zenodo',blow)),
     'variability':bool(re.search(r'±|standard deviation|\bstd\b|confidence interval|error bar|\\pm|s\.d\.',low)),
     'limitation':bool(re.search(r'limitation',low)),'seed':bool(re.search(r'\bseeds?\b',low)),
     'has_refs_heading':bool(m)})
json.dump(rows,open(out,'w'),indent=1)
print('done',len(rows))
